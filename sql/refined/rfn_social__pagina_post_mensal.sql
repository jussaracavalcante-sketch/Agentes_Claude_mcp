WITH base AS (
  SELECT
    _fonte AS fonte, id_pagina, mes_referencia,
    COUNT(*)                                        AS qtd_posts,
    COUNTIF(tipo_post = 'added_photos')             AS qtd_fotos,
    COUNTIF(tipo_post = 'added_video')              AS qtd_videos,
    COUNTIF(tipo_post IS NULL OR tipo_post NOT IN ('added_photos', 'added_video')) AS qtd_outros_tipos,
    COUNTIF(mensagem IS NOT NULL)                   AS qtd_com_texto,
    COUNTIF(NOT flag_sem_insight)                   AS qtd_com_insight,
    MIN(data_local)                                 AS primeira_postagem,
    MAX(data_local)                                 AS ultima_postagem,
    SUM(cliques)                                    AS cliques,
    SUM(reacoes_curtir)                             AS reacoes_curtir,
    SUM(reacoes_amei)                               AS reacoes_amei,
    SUM(reacoes_uau)                                AS reacoes_uau,
    SUM(reacoes_haha)                               AS reacoes_haha,
    SUM(reacoes_triste)                             AS reacoes_triste,
    SUM(reacoes_grr)                                AS reacoes_grr,
    SUM(compartilhamentos)                          AS compartilhamentos,
    COUNTIF(compartilhamentos IS NOT NULL)          AS qtd_com_compartilhamento_informado,
    SUM(video_views_autoplay)                       AS video_views_autoplay,
    SUM(video_views_clique_para_reproduzir)         AS video_views_clique_para_reproduzir,
    SUM(video_views_com_som)                        AS video_views_com_som,
    SUM(video_views_15s)                            AS video_views_15s,
    SUM(video_views_completas_organicas)            AS video_views_completas_organicas,
    SUM(media_views)                                AS media_views,
    SUM(media_views_de_anuncio)                     AS media_views_de_anuncio,
    SUM(media_views_organicas)                      AS media_views_organicas,
    SUM(media_views_de_seguidores)                  AS media_views_de_seguidores,
    SUM(media_views_de_nao_seguidores)              AS media_views_de_nao_seguidores
  FROM `vanguardamartech_trusted`.`trs_facebook_pages__post`
  GROUP BY 1, 2, 3
)
SELECT
  CONCAT(b.fonte, ':', b.id_pagina, ':', CAST(b.mes_referencia AS STRING))   AS id_pagina_mes,
  b.fonte,
  b.id_pagina,
  p.nome                                                                     AS nome_pagina,
  p.categoria                                                                AS categoria_pagina,
  b.mes_referencia,
  b.qtd_posts,
  b.qtd_fotos,
  b.qtd_videos,
  b.qtd_outros_tipos,
  b.qtd_com_texto,
  b.qtd_com_insight,
  b.primeira_postagem,
  b.ultima_postagem,
  b.cliques,
  b.reacoes_curtir,
  b.reacoes_amei,
  b.reacoes_uau,
  b.reacoes_haha,
  b.reacoes_triste,
  b.reacoes_grr,
  IF(COALESCE(b.reacoes_curtir, b.reacoes_amei, b.reacoes_uau, b.reacoes_haha, b.reacoes_triste, b.reacoes_grr) IS NULL, NULL,
     IFNULL(b.reacoes_curtir, 0) + IFNULL(b.reacoes_amei, 0) + IFNULL(b.reacoes_uau, 0)
     + IFNULL(b.reacoes_haha, 0) + IFNULL(b.reacoes_triste, 0) + IFNULL(b.reacoes_grr, 0)) AS reacoes_total,
  b.compartilhamentos,
  b.qtd_com_compartilhamento_informado,
  b.video_views_autoplay,
  b.video_views_clique_para_reproduzir,
  b.video_views_com_som,
  b.video_views_15s,
  b.video_views_completas_organicas,
  b.media_views,
  b.media_views_de_anuncio,
  b.media_views_organicas,
  b.media_views_de_seguidores,
  b.media_views_de_nao_seguidores,
  ROUND(SAFE_DIVIDE(b.media_views, NULLIF(b.qtd_com_insight, 0)), 2)         AS media_views_por_post_com_insight,
  ROUND(SAFE_DIVIDE(b.cliques, NULLIF(b.qtd_com_insight, 0)), 2)             AS cliques_por_post_com_insight,
  SAFE_DIVIDE(b.qtd_videos, b.qtd_posts)                                     AS participacao_video_nos_posts,
  (p.id_pagina IS NULL)                                                      AS flag_pagina_nao_catalogada,
  CURRENT_TIMESTAMP()                                                        AS _extraido_at,
  'facebook-pages'                                                           AS _fonte
FROM base b
LEFT JOIN `vanguardamartech_trusted`.`trs_facebook_pages__pagina` p ON p._fonte = b.fonte AND p.id_pagina = b.id_pagina
